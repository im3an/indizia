// Markdown exports: the investigation report and the pinned case. Every claim keeps its citation.

import { DISPLAY } from './detect.js';

const CONF = { confirmed: 'Confirmed', corroborated: 'Corroborated', plausible: 'Plausible', conflict: 'Conflicting', lead: 'Unverified lead' };
export const STATE_LABEL = {
  queued: 'Queued', running: 'Querying', done: 'Answered', empty: 'Nothing found', rate_limited: 'Rate-limited',
  failed: 'Failed', timeout: 'Timed out', needs_relay: 'Needs relay', standby: 'Standby', skipped: 'Not needed', not_applicable: 'Not applicable',
};

function cite(ev) {
  if (!ev) return '';
  return ` — ${ev.url} (retrieved ${ev.retrievedAt}${ev.sha256 ? `, sha256 ${ev.sha256.slice(0, 16)}…` : ''}${ev.viaRelay ? ', via relay' : ''})`;
}

export function investigationMarkdown(state) {
  const r = state.root;
  const lines = [];
  lines.push(`# Indizia report: ${r.value}`, '');
  lines.push(`- **Input type:** ${DISPLAY[r.type] || r.type}`);
  lines.push(`- **Started:** ${state.startedAt}`);
  lines.push(`- **Finished:** ${state.finishedAt || 'still running'}`);
  const real = state.runs.filter((x) => x.state !== 'not_applicable');
  lines.push(`- **Sources:** ${real.filter((x) => x.state === 'done').length} answered of ${real.length} applicable · ${state.launches.length} manual launch pads not searched`, '');
  lines.push('> Generated by the Indizia prototype from public sources. Two separate ratings: the confidence label rates each claim; the letter grade A–F (Admiralty scale) rates the source in general. Plausible matches and leads are unverified.', '');

  for (const [group, facts] of Object.entries(state.facts)) {
    lines.push(`## ${group}`, '');
    for (const f of facts) {
      lines.push(`- **${f.label}:** ${f.value} _(${f.sources.map((s) => s.name).join(', ')}; ${CONF[f.confidence] || f.confidence})_`);
    }
    lines.push('');
  }

  lines.push('## Findings', '');
  for (const f of state.findings) {
    lines.push(`- **[${f.id}] ${CONF[f.confidence] || f.confidence}:** ${f.title}${f.detail ? `. ${f.detail}` : ''}`);
    lines.push(`  - Source: ${f.source.name}${f.source.reliability ? ` [reliability ${f.source.reliability}: ${f.source.reliabilityLabel}]` : ''}${f.via ? ` (via ${f.via})` : ''}${cite(f.evidence)}`);
    if (f.list?.length) lines.push(`  - ${f.listLabel}: ${f.list.join(', ')}`);
  }
  lines.push('');

  const pivots = state.pivots || [];
  if (pivots.length) {
    const b = state.budget || {};
    lines.push('## Pivots', '', `Indizia follows links on its own up to ${b.depth} step(s) from the search and ${b.budget} source runs (${b.spent} used). Held pivots were not searched.`, '');
    lines.push('| Step | From | Link | To | Status |', '|---|---|---|---|---|');
    const cell = (s) => String(s ?? '').replace(/\|/g, '/');
    for (const p of pivots) {
      const status = p.status === 'held' ? `held (${p.held})` : p.manual ? 'followed by the user' : 'followed automatically';
      lines.push(`| ${p.hop} | ${cell(p.from?.label || p.from?.value)} | ${cell(p.reason)}${p.source ? ` (${cell(p.source)})` : ''} | ${cell(p.entity.label || p.entity.value)} | ${status} |`);
    }
    lines.push('');
  }
  if (state.questions?.length) {
    lines.push('## Open questions', '');
    for (const q of state.questions) lines.push(`- ${q.text}${q.weak ? ' _(weak lead)_' : ''}${q.why ? ` — ${q.why}` : ''}`);
    lines.push('');
  }

  lines.push('## Coverage ledger', '', '| Source | Input | State | Time | Note |', '|---|---|---|---|---|');
  for (const x of state.runs) {
    const note = [x.via && `via ${x.via}`, x.message, ...x.notes].filter(Boolean).join('; ').replace(/\|/g, '/');
    lines.push(`| ${x.source.name} | ${x.entity.value} | ${STATE_LABEL[x.state]} | ${x.ms != null ? x.ms + ' ms' : '—'} | ${note} |`);
  }
  lines.push('', '## Not searched (manual launch pads)', '');
  for (const l of state.launches) lines.push(`- ${l.name}: ${l.href}${l.copy ? ` (query: ${l.copy})` : ''}`);
  lines.push('');
  return lines.join('\n');
}

export function caseMarkdown(items) {
  const lines = ['# Indizia case', '', `Exported ${new Date().toISOString()}`, ''];
  for (const it of items) {
    lines.push(`- **${CONF[it.confidence] || it.confidence}:** ${it.title}${it.detail ? `. ${it.detail}` : ''}`);
    lines.push(`  - From the investigation of "${it.query}" · ${it.source}${it.url ? ` — ${it.url}` : ''}${it.retrievedAt ? ` (retrieved ${it.retrievedAt})` : ''}`);
  }
  return lines.join('\n') + '\n';
}

export function download(filename, text) {
  const blob = new Blob([text], { type: 'text/markdown;charset=utf-8' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    URL.revokeObjectURL(a.href);
    a.remove();
  }, 0);
}

export const CONFIDENCE_LABEL = CONF;
